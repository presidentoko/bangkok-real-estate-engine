"""Rename condo slugs whose city suffix contradicts the building's province.

backfill_condo_slug.py builds a slug as {name}-{province} at the moment a
condo first gets one. When a later pass corrects the province — the
normalisation sweep, a re-match against a better listing — the slug keeps
the old city. On 2026-09-23 that was 1,206 slugs: 744 Pattaya buildings and
431 Hua Hin buildings whose URL ended in "-bangkok".

Only indexable buildings are renamed (58 of the 1,206; the rest are noindex
stubs, so a rename would churn the Cloudflare export for pages Google is
told to ignore). The old slug is recorded in
web/lib/condoSlugRedirects.ts, which next.config.mjs turns into platform
308s — no function invocation, and the Worker passes an unknown /condo/ URL
through to Vercel where those redirects live.

    python scripts/repair_condo_slug_city.py            # dry run
    python scripts/repair_condo_slug_city.py --apply
"""
from __future__ import annotations

import argparse
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

from dotenv import load_dotenv  # noqa: E402

load_dotenv(os.path.join(ROOT, ".env"))

from loguru import logger  # noqa: E402

from src.db import get_client  # noqa: E402

REDIRECTS_TS = os.path.join(ROOT, "web", "lib", "condoSlugRedirects.ts")
REDIRECTS_MJS = os.path.join(ROOT, "web", "lib", "condoSlugRedirects.mjs")

# Every city word a slug may end in, and the canonical province spelling it
# should match (web/lib/cities.ts keeps the same aliases for the UI).
CITY_ALIASES = {
    "chiang-mai": "chiangmai",
    "hua-hin": "huahin",
    "chon-buri": "chonburi",
    "ko-samui": "samui",
}
CITY_WORDS = [
    "bangkok", "pattaya", "phuket", "chiang-mai", "chiangmai", "hua-hin", "huahin",
    "chon-buri", "chonburi", "ko-samui", "samui", "krabi", "nonthaburi",
    "samut-prakan", "pathum-thani", "chiang-rai", "chiangrai",
]

INDEXABLE_COLUMNS = (
    "active_listings_count, market_sale_median, market_rent_median, "
    "gross_yield_pct, description, google_review_count"
)


def canon(x: str) -> str:
    return CITY_ALIASES.get(x, x)


def has_substance(r: dict) -> bool:
    """Mirror of hasIndexableSubstance() in web/lib/condoIndexability.ts."""
    if (r.get("active_listings_count") or 0) >= 1:
        return True
    if r.get("market_sale_median") is not None:
        return True
    if r.get("market_rent_median") is not None:
        return True
    if r.get("gross_yield_pct") is not None:
        return True
    if len((r.get("description") or "").strip()) >= 120:
        return True
    if (r.get("google_review_count") or 0) >= 3:
        return True
    return False


def fetch_all(client, table: str, columns: str) -> list[dict]:
    out: list[dict] = []
    offset = 0
    while True:
        page = (
            client.table(table).select(columns).order("id").range(offset, offset + 999).execute().data
        ) or []
        out.extend(page)
        if len(page) < 1000:
            break
        offset += 1000
    return out


def wrong_city(slug: str, province: str | None) -> str | None:
    """The city word this slug ends in, when it contradicts the province."""
    for w in CITY_WORDS:
        if slug.endswith("-" + w):
            return w if canon(w) != canon(province or "") else None
    return None


def load_existing_redirects() -> list[tuple[str, str]]:
    if not os.path.exists(REDIRECTS_TS):
        return []
    body = open(REDIRECTS_TS, encoding="utf-8").read()
    return re.findall(r'\{ from: "([^"]+)", to: "([^"]+)" \}', body)


def write_redirects(pairs: list[tuple[str, str]]) -> None:
    lines = "\n".join('  { from: "%s", to: "%s" },' % (a, b) for a, b in pairs)
    header = (
        "// Generated by scripts/repair_condo_slug_city.py - do not edit by hand.\n"
        "//\n"
        "// A condo whose province was corrected after its slug was minted kept the\n"
        "// old city in its URL (a Pattaya building ending in -bangkok). Renaming the\n"
        "// slug moves the page, so the old URL redirects here, as a platform 308 in\n"
        "// next.config.mjs.\n"
    )
    with open(REDIRECTS_TS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        fh.write("export const CONDO_SLUG_REDIRECTS: Array<{ from: string; to: string }> = [\n")
        fh.write(lines + "\n];\n")
    # next.config.mjs is ESM and cannot import TypeScript, so the list is
    # emitted twice and both files are committed together.
    with open(REDIRECTS_MJS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header)
        fh.write("export const CONDO_SLUG_REDIRECTS = [\n")
        fh.write(lines + "\n];\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="write (default: dry run)")
    ap.add_argument("--all", action="store_true", help="include noindex stubs too")
    args = ap.parse_args()

    client = get_client()
    rows = fetch_all(client, "condos_published", f"id, slug, name, province, {INDEXABLE_COLUMNS}")
    taken = {r["slug"] for r in rows if r.get("slug")}

    renames: list[tuple[str, str, str]] = []  # id, old, new
    for r in rows:
        slug, province = r.get("slug"), r.get("province")
        if not slug:
            continue
        bad = wrong_city(slug, province)
        if not bad:
            continue
        if not args.all and not has_substance(r):
            continue
        stem = slug[: -(len(bad) + 1)]
        # "supalai-mare-pattaya-bangkok" is already named for its city, and
        # "baan-had-hua-hin-condo-bangkok" carries it mid-name: appending the
        # province again would give ...-pattaya-pattaya. Only add it when the
        # name does not already say it.
        stem_tokens = stem.split("-")
        prov_tokens = (province or "").split("-")
        already = any(
            stem_tokens[i : i + len(prov_tokens)] == prov_tokens
            for i in range(len(stem_tokens) - len(prov_tokens) + 1)
        )
        base = stem if already else f"{stem}-{province}"
        new = base
        n = 2
        while new in taken:
            new = f"{base}-{n}"
            n += 1
        taken.add(new)
        renames.append((r["id"], slug, new))

    logger.info(f"{len(renames)} slugs to rename")
    for _, old, new in renames[:10]:
        logger.info(f"  {old}  ->  {new}")
    if len(renames) > 10:
        logger.info(f"  ... and {len(renames) - 10} more")

    if not args.apply:
        logger.info("dry run — pass --apply to write")
        return 0

    done = 0
    for uid, _old, new in renames:
        client.table("condos").update({"slug": new}).eq("id", uid).execute()
        done += 1
    logger.info(f"updated {done} rows")

    pairs = load_existing_redirects()
    known = {a for a, _ in pairs}
    # A slug renamed twice must still land on the current URL, so rewrite any
    # existing entry that pointed at a slug we just moved again.
    moved = {old: new for _, old, new in renames}
    pairs = [(a, moved.get(b, b)) for a, b in pairs]
    pairs += [(old, new) for _, old, new in renames if old not in known]
    write_redirects(sorted(set(pairs)))
    logger.info(f"{REDIRECTS_TS}: {len(pairs)} redirects")
    return 0


if __name__ == "__main__":
    sys.exit(main())
