"""Regenerate web/lib/doohongBuildings.ts, the building-name -> DooHong slug map.

Condo pages link to the same building on DooHong (doohong.com, the founder's
Bangkok condo-interiors site) when DooHong has a page for it, else to
DooHong's home. The page never calls DooHong at build or request time: it
looks the building up in this static file.

    python scripts/doohong/gen_doohong_map.py
    python scripts/doohong/gen_doohong_map.py --check-live --manifest store/manifest.txt

Inputs (defaults point at the DooHong checkout on the founder's machine):

--csv       DooHong's collected projects (columns slug, name_en).
--imported  DooHong's merged CSV, i.e. what was actually imported to
            production. Rows of --csv that are not in it have no live page
            and are dropped. Skipped when the file does not exist.
--check-live  Additionally GET https://doohong.com/en/condo/<slug> for each
            row and drop anything that is not a 200. Slow (one request per
            building); use it before committing a regenerated map.
--manifest  Optional condo-static store manifest (`lang/slug` per line, see
            .github/workflows/condo-static.yml) -- only used to print how many
            RealData pages the map will match.

Keys are the building's English name run through the same slugify as
scripts/backfill_condo_slug.py (and web/lib/doohong.ts), so a RealData condo
matches when its name normalises to the same string. The DooHong slug itself
is added as a second key. A key claimed by two different DooHong slugs is
dropped rather than guessed.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
import unicodedata
import urllib.error
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "web" / "lib" / "doohongBuildings.ts"
DEFAULT_CSV = Path(r"C:\Users\yn\Desktop\오늘의집\data\scraped\projects.csv")

# Provinces whose condos can be the same building as a DooHong project
# (DooHong covers Bangkok plus Samut Prakan / Nonthaburi districts). Must match
# GREATER_BANGKOK in web/lib/doohong.ts.
GREATER_BANGKOK = ("bangkok", "samut-prakan", "nonthaburi", "pathum-thani")


def slugify(text: str) -> str:
    """Same as scripts/backfill_condo_slug.py:slugify."""
    if not text:
        return ""
    text = unicodedata.normalize("NFKD", text)
    text = text.encode("ascii", "ignore").decode("ascii").lower()
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-")


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def is_live(slug: str) -> bool:
    req = urllib.request.Request(
        f"https://doohong.com/en/condo/{slug}",
        headers={"User-Agent": "passionaryestate-doohong-map/1"},
    )
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status == 200
    except urllib.error.HTTPError:
        return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    ap.add_argument("--imported", type=Path, default=None)
    ap.add_argument("--check-live", action="store_true")
    ap.add_argument("--manifest", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()

    rows = read_rows(args.csv)
    imported_path = args.imported or args.csv.parent / "merged" / "projects.csv"
    if imported_path.exists():
        imported = {r["slug"].strip() for r in read_rows(imported_path)}
        dropped = [r["slug"] for r in rows if r["slug"].strip() not in imported]
        rows = [r for r in rows if r["slug"].strip() in imported]
        print(f"{len(rows)} rows imported to DooHong; {len(dropped)} not imported, dropped")

    if args.check_live:
        live = []
        for r in rows:
            if is_live(r["slug"].strip()):
                live.append(r)
            else:
                print(f"  not live, dropped: {r['slug']}")
        rows = live
        print(f"{len(rows)} live on doohong.com")

    claims: dict[str, set[str]] = {}
    for r in rows:
        slug = r["slug"].strip()
        for key in {slugify(r.get("name_en", "")), slugify(slug)}:
            if key:
                claims.setdefault(key, set()).add(slug)

    buildings = {}
    for key, slugs in sorted(claims.items()):
        if len(slugs) > 1:
            print(f"  ambiguous key {key!r} -> {sorted(slugs)}, dropped")
            continue
        buildings[key] = next(iter(slugs))

    body = json.dumps(buildings, ensure_ascii=False, indent=2)
    args.out.write_text(
        "// Generated by scripts/doohong/gen_doohong_map.py -- do not edit by hand.\n"
        "// RealData building name (slugified, see lib/doohong.ts) -> DooHong slug.\n"
        f"export const DOOHONG_BUILDINGS: Record<string, string> = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(buildings)} keys ({len(set(buildings.values()))} DooHong buildings) -> {args.out}")

    if args.manifest:
        # RealData slugs are slugify(name)-<province>[-suffix]
        # (backfill_condo_slug.py:make_slug), so a page matches when its slug
        # is a key followed by a greater-Bangkok province.
        prov = "|".join(map(re.escape, GREATER_BANGKOK))
        pages, hit_slugs = 0, set()
        en = [
            l.strip()[3:]
            for l in args.manifest.read_text(encoding="utf-8").splitlines()
            if l.startswith("en/")
        ]
        for s in en:
            for key, dh in buildings.items():
                if re.match(re.escape(key) + rf"-(?:{prov})(?:-|$)", s):
                    pages += 1
                    hit_slugs.add(dh)
                    break
        print(
            f"manifest: {pages} of {len(en)} RealData condo pages per locale match "
            f"{len(hit_slugs)} of {len(set(buildings.values()))} DooHong buildings"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
